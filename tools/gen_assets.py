"""Writes src/assets.rs: the table of scenes and fonts that get built into the exe.

    python tools/gen_assets.py
"""

import glob
import json
import os
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
NAMES = {
    "noto-naskh-arabic": "Noto Naskh Arabic", "scheherazade-new": "Scheherazade New", "lateef": "Lateef", "amiri": "Amiri",
    "ibm-plex-sans-arabic": "IBM Plex Sans Arabic", "tajawal": "Tajawal", "almarai": "Almarai", "readex-pro": "Readex Pro",
    "cairo": "Cairo", "noto-kufi-arabic": "Noto Kufi Arabic", "reem-kufi": "Reem Kufi",
    "noto-sans-bengali": "Noto Sans Bengali", "hind-siliguri": "Hind Siliguri", "tiro-bangla": "Tiro Bangla", "baloo-da-2": "Baloo Da 2",
    "geist": "Geist", "manrope": "Manrope", "plus-jakarta-sans": "Plus Jakarta Sans", "inter": "Inter", "outfit": "Outfit",
    "sora": "Sora", "dm-sans": "DM Sans", "urbanist": "Urbanist", "fraunces": "Fraunces", "playfair-display": "Playfair Display",
    "lora": "Lora", "jetbrains-mono": "JetBrains Mono",
}
from fetch_fonts import ARABIC, BANGLA, ENGLISH

GROUPS = {"ARABIC": ARABIC, "BANGLA": BANGLA, "ENGLISH": ENGLISH}
FAMILIES = json.loads((ROOT / "assets/fonts/families.json").read_text(encoding="utf-8")) if (ROOT / "assets/fonts/families.json").exists() else {}


def rs(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)  # a JSON string is a valid Rust string literal here


def main():
    scenes = json.loads((ROOT / "assets/scenes/scenes.json").read_text(encoding="utf-8"))
    files = {}
    for f in sorted(glob.glob(str(ROOT / "assets/fonts/*.ttf"))):
        name = os.path.basename(f)
        files.setdefault(name[:-4].rsplit("-", 1)[0], []).append(name)

    out = [
        "//! Everything the wallpaper ships with, built into the exe so one file is the whole app.",
        "//! Generated by tools/gen_assets.py. Photos: Wikimedia Commons (see CREDITS.md). Fonts: SIL OFL.",
        "",
        "pub struct Scene {",
        "    pub id: &'static str,",
        "    pub name: &'static str,",
        "    pub credit: &'static str,",
        "    pub source: &'static str,",
        "    pub jpg: &'static [u8],",
        "}",
        "",
        "pub struct Font {",
        "    pub name: &'static str,",
        "    pub files: &'static [&'static [u8]],",
        "}",
        "",
        "macro_rules! scene {",
        "    ($id:literal, $name:literal, $credit:literal, $source:literal) => {",
        '        Scene { id: $id, name: $name, credit: $credit, source: $source, jpg: include_bytes!(concat!("../assets/scenes/", $id, ".jpg")) }',
        "    };",
        "}",
        "",
        "macro_rules! font {",
        "    ($name:literal, $($file:literal),+) => {",
        '        Font { name: $name, files: &[$(include_bytes!(concat!("../assets/fonts/", $file))),+] }',
        "    };",
        "}",
        "",
        "pub static SCENES: &[Scene] = &[",
    ]
    for s in scenes:
        out.append(f"    scene!({rs(s['id'])}, {rs(s['name'])}, {rs(s['credit'])}, {rs(s['source'])}),")
    out.append("];")
    for group, ids in GROUPS.items():
        out += ["", f"pub static {group}_FONTS: &[Font] = &["]
        for i in ids:
            if i not in files:
                continue
            out.append(f"    font!({rs(NAMES.get(i) or FAMILIES.get(i, i))}, {', '.join(rs(f) for f in files[i])}),")
        out.append("];")
    # Calligraphy scenes (tools/calligraphy/export.py): an SVG background plus where the lettering goes.
    kufi = {"RK": "Reem Kufi", "NK": "Noto Kufi Arabic", "KF": "Kufam", "EM": "El Messiri", "CH": "Changa",
            "AX": "Alexandria", "LZ": "Lalezar", "RD": "Readex Pro"}
    cal = json.loads((ROOT / "assets/calligraphy/scenes.json").read_text(encoding="utf-8"))
    f32 = lambda v: f"{float(v)}_f32"
    out += [
        "",
        "pub struct Watermark {",
        "    pub text: &'static str,",
        "    pub x: f32,",
        "    pub y: f32,",
        "    pub size: f32,",
        "    pub color: &'static str,",
        "    pub font: &'static str,",
        "}",
        "",
        "/// A calligraphy scene. Coordinates are in a 1600×900 picture whose lettering column is the left 62%.",
        "pub struct Calligraphy {",
        "    pub id: &'static str,",
        "    pub name: &'static str,",
        "    /// Shown by itself in Ramadan, on Eid and on Arafah, not picked by hand.",
        "    pub occasion: bool,",
        "    pub lines: &'static [&'static str],",
        "    pub meaning: &'static str,",
        "    pub reference: &'static str,",
        "    pub font: &'static str,",
        "    pub ink: &'static str,",
        "    /// Colour of the clock panel's text on this scene, and its accent.",
        "    pub panel: &'static str,",
        "    pub accent: &'static str,",
        "    pub scale: f32,",
        "    /// left, top, right, bottom of the lettering box",
        "    pub bx: [f32; 4],",
        "    pub no_meaning: bool,",
        "    pub watermark: Option<Watermark>,",
        "    pub grain: f32,",
        "    pub svg: &'static str,",
        "}",
        "",
        "pub static CALLIGRAPHY: &[Calligraphy] = &[",
    ]
    for d in cal:
        wm = d.get("watermark")
        wms = "None" if not wm else f"Some(Watermark {{ text: {rs(wm['t'])}, x: {f32(wm['x'])}, y: {f32(wm['y'])}, size: {f32(wm['size'])}, color: {rs(wm['c'])}, font: {rs(kufi[wm['f']])} }})"
        out.append(
            f"    Calligraphy {{ id: {rs(d['id'])}, name: {rs(d['name'])}, occasion: {str(d['occasion']).lower()}, "
            f"lines: &[{', '.join(rs(x) for x in d['ar'])}], meaning: {rs(d['en'])}, reference: {rs(d['ref'])}, "
            f"font: {rs(kufi[d['font']])}, ink: {rs(d['ink'])}, panel: {rs(d['panel'])}, accent: {rs(d['accent'])}, "
            f"scale: {f32(d['scale'])}, bx: [{', '.join(f32(v) for v in d['box'])}], no_meaning: {str(d['no_meaning']).lower()}, "
            f"watermark: {wms}, grain: {f32(d['grain'])}, svg: include_str!(\"../assets/calligraphy/{d['id']}.svg\") }},"
        )
    out.append("];")
    out += [
        "",
        "/// Offline library of Quran verses, hadith and adhkar (built by tools/build_content.py).",
        'pub static CONTENT: &str = include_str!("../assets/content.json");',
        "",
    ]
    (ROOT / "src/assets.rs").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
