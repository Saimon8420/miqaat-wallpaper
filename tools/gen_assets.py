"""Writes src/assets.rs: the table of scenes and fonts that get built into the exe.

    python tools/gen_assets.py
"""

import glob
import json
import os
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
NAMES = {
    "noto-naskh-arabic": "Noto Naskh Arabic", "scheherazade-new": "Scheherazade New", "lateef": "Lateef", "amiri": "Amiri",
    "ibm-plex-sans-arabic": "IBM Plex Sans Arabic", "tajawal": "Tajawal", "almarai": "Almarai", "readex-pro": "Readex Pro",
    "cairo": "Cairo", "noto-kufi-arabic": "Noto Kufi Arabic", "reem-kufi": "Reem Kufi",
    "noto-sans-bengali": "Noto Sans Bengali", "hind-siliguri": "Hind Siliguri", "tiro-bangla": "Tiro Bangla", "baloo-da-2": "Baloo Da 2",
    "geist": "Geist", "manrope": "Manrope", "plus-jakarta-sans": "Plus Jakarta Sans", "inter": "Inter", "outfit": "Outfit",
    "sora": "Sora", "dm-sans": "DM Sans", "urbanist": "Urbanist", "fraunces": "Fraunces", "playfair-display": "Playfair Display",
    "lora": "Lora", "jetbrains-mono": "JetBrains Mono",
}
GROUPS = {
    "ARABIC": ["noto-naskh-arabic", "scheherazade-new", "lateef", "amiri", "ibm-plex-sans-arabic", "tajawal", "almarai",
               "readex-pro", "cairo", "noto-kufi-arabic", "reem-kufi"],
    "BANGLA": ["noto-sans-bengali", "hind-siliguri", "tiro-bangla", "baloo-da-2"],
    "ENGLISH": ["geist", "manrope", "plus-jakarta-sans", "inter", "outfit", "sora", "dm-sans", "urbanist", "fraunces",
                "playfair-display", "lora", "jetbrains-mono"],
}


def rs(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)  # a JSON string is a valid Rust string literal here


def main():
    scenes = json.loads((ROOT / "assets/scenes/scenes.json").read_text(encoding="utf-8"))
    files = {}
    for f in sorted(glob.glob(str(ROOT / "assets/fonts/*.ttf"))):
        name = os.path.basename(f)
        files.setdefault(name[:-4].rsplit("-", 1)[0], []).append(name)

    out = [
        "//! Everything the wallpaper ships with, built into the exe so one file is the whole app.",
        "//! Generated by tools/gen_assets.py. Photos: Wikimedia Commons (see CREDITS.md). Fonts: SIL OFL.",
        "",
        "pub struct Scene {",
        "    pub id: &'static str,",
        "    pub name: &'static str,",
        "    pub credit: &'static str,",
        "    pub source: &'static str,",
        "    pub jpg: &'static [u8],",
        "}",
        "",
        "pub struct Font {",
        "    pub name: &'static str,",
        "    pub files: &'static [&'static [u8]],",
        "}",
        "",
        "macro_rules! scene {",
        "    ($id:literal, $name:literal, $credit:literal, $source:literal) => {",
        '        Scene { id: $id, name: $name, credit: $credit, source: $source, jpg: include_bytes!(concat!("../assets/scenes/", $id, ".jpg")) }',
        "    };",
        "}",
        "",
        "macro_rules! font {",
        "    ($name:literal, $($file:literal),+) => {",
        '        Font { name: $name, files: &[$(include_bytes!(concat!("../assets/fonts/", $file))),+] }',
        "    };",
        "}",
        "",
        "pub static SCENES: &[Scene] = &[",
    ]
    for s in scenes:
        out.append(f"    scene!({rs(s['id'])}, {rs(s['name'])}, {rs(s['credit'])}, {rs(s['source'])}),")
    out.append("];")
    for group, ids in GROUPS.items():
        out += ["", f"pub static {group}_FONTS: &[Font] = &["]
        for i in ids:
            out.append(f"    font!({rs(NAMES[i])}, {', '.join(rs(f) for f in files[i])}),")
        out.append("];")
    out += [
        "",
        "/// Offline library of Quran verses, hadith and adhkar (built by tools/build_content.py).",
        'pub static CONTENT: &str = include_str!("../assets/content.json");',
        "",
    ]
    (ROOT / "src/assets.rs").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
